import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const hydratorPath = new URL('../internal/web/static/request-composer-hydrator.js', import.meta.url);
const outputPath = new URL('../internal/web/static/request-composer.js', import.meta.url);

const vendor = await build({
  stdin: {
    contents: `
      import { Buffer } from 'buffer';
      import { HTTPSnippet } from '@readme/httpsnippet';
      import hljs from 'highlight.js/lib/core';
      import bash from 'highlight.js/lib/languages/bash';
      import javascript from 'highlight.js/lib/languages/javascript';
      import python from 'highlight.js/lib/languages/python';
      import go from 'highlight.js/lib/languages/go';
      import java from 'highlight.js/lib/languages/java';
      import php from 'highlight.js/lib/languages/php';
      import ruby from 'highlight.js/lib/languages/ruby';
      import csharp from 'highlight.js/lib/languages/csharp';
      import powershell from 'highlight.js/lib/languages/powershell';
      import swift from 'highlight.js/lib/languages/swift';
      import kotlin from 'highlight.js/lib/languages/kotlin';
      import http from 'highlight.js/lib/languages/http';
      import c from 'highlight.js/lib/languages/c';
      import clojure from 'highlight.js/lib/languages/clojure';
      import objectivec from 'highlight.js/lib/languages/objectivec';
      import ocaml from 'highlight.js/lib/languages/ocaml';
      import r from 'highlight.js/lib/languages/r';

      if (!globalThis.Buffer) {
        globalThis.Buffer = Buffer;
      }
      Object.entries({
        bash,
        javascript,
        python,
        go,
        java,
        php,
        ruby,
        csharp,
        powershell,
        swift,
        kotlin,
        http,
        c,
        clojure,
        objectivec,
        ocaml,
        r,
      }).forEach(([name, language]) => hljs.registerLanguage(name, language));
      globalThis.ManjaHTTPSnippet = { HTTPSnippet };
      globalThis.ManjaHighlight = hljs;
    `,
    loader: 'js',
    resolveDir: projectRoot,
    sourcefile: 'request-composer-vendor.js',
  },
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  write: false,
  logLevel: 'silent',
  define: {
    'process.env.NODE_ENV': '"production"',
  },
});

const hydrator = await readFile(hydratorPath, 'utf8');
const vendorCode = stripTrailingWhitespace(vendor.outputFiles[0].text);

await writeFile(
  outputPath,
  [
    '// Code generated by scripts/build-request-composer-asset.mjs; DO NOT EDIT.',
    vendorCode.trimEnd(),
    ';',
    stripTrailingWhitespace(hydrator).trimEnd(),
    '',
  ].join('\n'),
);

function stripTrailingWhitespace(value) {
  return value.replace(/[ \t]+$/gm, '');
}

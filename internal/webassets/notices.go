package webassets

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

func renderNotices(bundles []Bundle, report Report) ([]byte, error) {
	if err := validateReportPackages(bundles, report.Bundles); err != nil {
		return nil, err
	}
	bundleByName := make(map[string]Bundle, len(bundles))
	for _, bundle := range bundles {
		bundleByName[bundle.Name] = bundle
	}
	reports := append([]BundleReport(nil), report.Bundles...)
	sort.Slice(reports, func(i, j int) bool { return reports[i].Name < reports[j].Name })
	var output bytes.Buffer
	output.WriteString("# Browser bundle license evidence\n\n")
	output.WriteString("<!-- Code generated by cmd/webassets; DO NOT EDIT. -->\n\n")
	output.WriteString("This inventory records the package code that enters Manja's committed browser bundles. Acquisition bytes and readable licenses are retained by Muamba with SHA-384 locks.\n\n")
	for _, bundleReport := range reports {
		bundle, ok := bundleByName[bundleReport.Name]
		if !ok {
			return nil, fmt.Errorf("report for unknown bundle %q", bundleReport.Name)
		}
		fmt.Fprintf(&output, "## %s\n\nOutput: `%s`\n\n", bundle.Name, bundleReport.Output)
		output.WriteString("| Package | Version | SPDX | Source | Muamba hash | Retained license | Included files |\n")
		output.WriteString("| --- | --- | --- | --- | --- | --- | --- |\n")
		packages := append([]Package(nil), bundle.Packages...)
		sort.Slice(packages, func(i, j int) bool { return packages[i].Name < packages[j].Name })
		for _, pkg := range packages {
			inputs := packageInputs(bundleReport.Inputs, pkg.Name)
			if len(inputs) == 0 {
				return nil, fmt.Errorf("bundle %q package %q has no included files", bundle.Name, pkg.Name)
			}
			licenseLink := "../../" + pkg.LicensePath
			fmt.Fprintf(&output, "| [%s](%s) | %s | %s | [archive](%s) | `%s` | [%s](%s) | %s |\n",
				markdownCell(pkg.Name), pkg.Homepage, pkg.Version, pkg.SPDX, pkg.ArchiveURL,
				pkg.ArchiveHash, markdownCell(pkg.LicensePath), licenseLink, codeList(inputs))
		}
		output.WriteByte('\n')
	}
	output.WriteString("Regenerate and verify with `go run ./cmd/webassets generate` and `go run ./cmd/webassets check`.\n")
	return output.Bytes(), nil
}

func packageInputs(inputs []string, packageName string) []string {
	var result []string
	for _, input := range inputs {
		if packageNameFromInput(input) == packageName {
			result = append(result, input)
		}
	}
	sort.Strings(result)
	return result
}

func codeList(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = "`" + markdownCell(value) + "`"
	}
	return strings.Join(quoted, "<br>")
}

func markdownCell(value string) string {
	return strings.ReplaceAll(value, "|", "\\|")
}

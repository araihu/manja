package webassets

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"unicode/utf8"

	"golang.org/x/text/cases"
)

// generateSearchNormalization keeps static search independent of a server and
// uses the index compiler's full Unicode case fold (not locale-sensitive lowercasing).
// Only this marked block in the otherwise handwritten search script is generated.
func generateSearchNormalization(root string) ([]byte, error) {
	input, err := os.ReadFile(filepath.Join(root, "internal/web/static/catalog-search.js"))
	if err != nil {
		return nil, err
	}
	const startMarker = "  // BEGIN GENERATED SEARCH CASE FOLD\n"
	const endMarker = "  // END GENERATED SEARCH CASE FOLD"
	start := bytes.Index(input, []byte(startMarker))
	end := bytes.Index(input, []byte(endMarker))
	if start < 0 || end < start {
		return nil, fmt.Errorf("search case fold markers are invalid")
	}
	fold := cases.Fold()
	mappings := make(map[string]string)
	for character := rune(0); character <= utf8.MaxRune; character++ {
		if !utf8.ValidRune(character) {
			continue
		}
		original := string(character)
		if folded := fold.String(original); folded != original {
			mappings[original] = folded
		}
	}
	var encoded bytes.Buffer
	encoder := json.NewEncoder(&encoded)
	encoder.SetEscapeHTML(false)
	if err := encoder.Encode(mappings); err != nil {
		return nil, err
	}
	block := "  // Code generated by cmd/webassets from golang.org/x/text/cases; DO NOT EDIT.\n  var searchCaseFold = " + strings.TrimSpace(encoded.String()) + ";\n"
	output := append([]byte{}, input[:start+len(startMarker)]...)
	output = append(output, block...)
	output = append(output, input[end:]...)
	return output, nil
}
